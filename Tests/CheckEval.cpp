    int runCheckEval (const juce::File& outDir, const juce::StringArray& wavs)
    {
        outDir.createDirectory();
        const Injection kinds[] { Injection::mud, Injection::boxy, Injection::sibilance, Injection::rumble, Injection::resonance, Injection::plosives };
        const bool withMix = juce::SystemStats::getEnvironmentVariable ("CHECK_EVAL_NOMIX", {}).isEmpty();

        struct Count { int tp = 0, n = 0, fp = 0; };
        std::map<int, Count> counts;
        int cleanFindings = 0, mixedFindings = 0, files = 0, cleanScoreSum = 0, mixedScoreSum = 0;
        std::map<juce::String, int> cleanIds, mixedIds;

        juce::String csv ("file,variant,score,findings,f0low,high,dev300,mudmax,mudat,dev700,boxmax,boxat,sib,sibhz,presence,rumble,plosives,resonances\n");
        // Full curves for offline detector design: file, variant, f0low, f0median, pitchedShare, then
        // tone (104), deviation (104), spectrum (104)
        juce::String curves;
        for (auto& path : wavs)
        {
            auto v = loadVocal (juce::File (path), 24.0);
            if (! v.has_value())
                continue;
            const auto name = juce::File (path).getFileNameWithoutExtension();
            ++files;

            std::vector<std::pair<Injection, dsp::AnalysisResult>> results;
            results.emplace_back (Injection::none, analyseCaptured (*v));
            for (auto k : kinds)
                results.emplace_back (k, analyseCaptured (inject (*v, k, (unsigned) files)));

            for (auto& [variant, r] : results)
            {
                juce::StringArray ids;
                for (auto& f : r.findings)
                    ids.add (f.id + "@" + juce::String (juce::roundToInt (f.freqHz)) + "(" + juce::String (f.confidence, 2) + ")");
                {
                    curves << name << "," << injectionName (variant) << "," << r.f0LowHz << "," << r.f0MedianHz << "," << r.pitchedShare;
                    for (auto* curve : { &r.toneDb, &r.deviationDb, &r.spectrumDb })
                        for (int b = 0; b < dsp::VocalAnalyzer::numBands; ++b)
                            curves << "," << juce::String (b < (int) curve->size() ? (*curve)[(size_t) b] : -200.0f, 2);
                    curves << "\n";
                }
                // Measurements behind the tonal rules (for threshold calibration)
                juce::String meas;
                const auto devAt = [&r] (float hz)
                {
                    const int b = juce::jlimit (0, dsp::VocalAnalyzer::numBands - 1, (int) std::lround (12.0 * std::log2 (hz / 40.0)));
                    return r.deviationDb.empty() ? 0.0f : r.deviationDb[(size_t) b];
                };
                const auto devMax = [&r] (float lo, float hi, float& at)
                {
                    float best = -100.0f;
                    for (int b = 0; b < (int) r.deviationDb.size(); ++b)
                    {
                        const float c = dsp::VocalAnalyzer::bandCentre (b);
                        if (c >= lo && c < hi && r.deviationDb[(size_t) b] > best)
                        {
                            best = r.deviationDb[(size_t) b];
                            at = c;
                        }
                    }
                    return best;
                };
                float mudAt = 0.0f, boxAt = 0.0f;
                const float mudMax = devMax (std::max (200.0f, r.pitchValid ? r.f0LowHz * 1.12f : 200.0f), 500.0f, mudAt);
                const float boxMax = devMax (500.0f, 1000.0f, boxAt);
                juce::StringArray res;
                for (auto& x : r.resonances)
                    res.add (juce::String (juce::roundToInt (x.hz)) + ":" + juce::String (x.excessDb, 1));
                meas << r.f0LowHz << "," << (r.highVoice ? 1 : 0) << "," << devAt (300.0f) << "," << mudMax << "," << mudAt << "," << devAt (700.0f) << ","
                     << boxMax << "," << boxAt << "," << (r.sibilanceValid ? r.sibilanceVsVowelDb : -100.0f) << "/" << r.sibilancePeakDb << "," << r.sibilanceHz << ","
                     << r.presenceDb << "," << r.rumbleDb << "," << r.plosiveCount << ",\"" << res.joinIntoString (" ") << "\"";
                csv << "\"" << name << "\"," << injectionName (variant) << "," << r.score << ",\"" << ids.joinIntoString (" ") << "\"," << meas << "\n";
                // Detection of each problem kind in this variant: TP when injected, else FP
                for (auto k : kinds)
                {
                    const bool injected = variant == k;
                    const bool found = detection (r, k) != nullptr;
                    bool anyOfKind = false;
                    for (auto& f : r.findings)
                        anyOfKind = anyOfKind || f.id.startsWith (injectionPrefix (k));
                    auto& c = counts[(int) k];
                    if (injected)
                    {
                        ++c.n;
                        c.tp += found ? 1 : 0;
                        // a finding of the kind at the wrong frequency is a false positive too
                        c.fp += (! found && anyOfKind) ? 1 : 0;
                    }
                    else if (variant == Injection::none)
                        c.fp += anyOfKind ? 1 : 0;
                }
                if (variant == Injection::none)
                {
                    cleanFindings += (int) r.findings.size();
                    cleanScoreSum += std::max (0, r.score);
                    for (auto& f : r.findings)
                        ++cleanIds[f.id.upToFirstOccurrenceOf (".", false, false)];
                }
            }

            juce::String mixLine;
            if (withMix)
                if (const auto mixed = autoMixed (*v))
                {
                    const auto r = analyseCaptured (*mixed);
                    mixedFindings += (int) r.findings.size();
                    mixedScoreSum += std::max (0, r.score);
                    juce::StringArray ids;
                    for (auto& f : r.findings)
                    {
                        ids.add (f.id + "@" + juce::String (juce::roundToInt (f.freqHz)) + "(" + juce::String (f.confidence, 2) + ")");
                        ++mixedIds[f.id.upToFirstOccurrenceOf (".", false, false)];
                    }
                    csv << "\"" << name << "\",automix," << r.score << ",\"" << ids.joinIntoString (" ") << "\"\n";
                    mixLine = " | mixed: score " + juce::String (r.score) + ", " + juce::String ((int) r.findings.size()) + " findings";
                }
            std::printf ("%-40s clean: score %3d, %d findings%s\n", name.toRawUTF8(), results.front().second.score,
                         (int) results.front().second.findings.size(), mixLine.toRawUTF8());
        }

        juce::String summary;
        summary << "Vocal Check evaluation, " << files << " files\n\n";
        summary << "problem        recall      precision   (TP / injected, FP on clean takes or wrong frequency)\n";
        int tpAll = 0, nAll = 0, fpAll = 0;
        for (auto k : kinds)
        {
            const auto& c = counts[(int) k];
            tpAll += c.tp; nAll += c.n; fpAll += c.fp;
            const float recall = c.n > 0 ? (float) c.tp / (float) c.n : 0.0f;
            const float precision = c.tp + c.fp > 0 ? (float) c.tp / (float) (c.tp + c.fp) : 1.0f;
            summary << juce::String (injectionName (k)).paddedRight (' ', 14) << " " << juce::String (recall, 2) << " (" << c.tp << "/" << c.n << ")   "
                    << juce::String (precision, 2) << " (FP " << c.fp << ")\n";
        }
        summary << "all            " << juce::String (nAll > 0 ? (float) tpAll / (float) nAll : 0.0f, 2) << "          "
                << juce::String (tpAll + fpAll > 0 ? (float) tpAll / (float) (tpAll + fpAll) : 1.0f, 2) << "\n\n";
        summary << "clean takes: " << cleanFindings << " findings, mean score " << (files > 0 ? cleanScoreSum / files : 0) << "\n";
        for (auto& [id, n] : cleanIds)
            summary << "  " << id << ": " << n << "\n";
        if (withMix)
        {
            summary << "auto-mixed: " << mixedFindings << " findings, mean score " << (files > 0 ? mixedScoreSum / files : 0) << "\n";
            for (auto& [id, n] : mixedIds)
                summary << "  " << id << ": " << n << "\n";
        }
        std::printf ("\n%s", summary.toRawUTF8());
        outDir.getChildFile ("check_eval.csv").replaceWithText (csv);
        outDir.getChildFile ("check_curves.csv").replaceWithText (curves);
        outDir.getChildFile ("check_eval_summary.txt").replaceWithText (summary);
        return 0;
    }
