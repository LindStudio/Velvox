    const char* injectionName (Injection i)
    {
        switch (i)
        {
            case Injection::none:      return "clean";
            case Injection::mud:       return "mud300";
            case Injection::boxy:      return "boxy700";
            case Injection::sibilance: return "sibilance7k";
            case Injection::rumble:    return "rumble";
            case Injection::resonance: return "resonance3k5";
            case Injection::plosives:  return "plosives";
        }
        return "?";
    }

    const char* injectionPrefix (Injection i)
    {
        switch (i)
        {
            case Injection::mud:       return "mud";
            case Injection::boxy:      return "boxy";
            case Injection::sibilance: return "sibilance";
            case Injection::rumble:    return "rumble";
            case Injection::resonance: return "resonance.";
            case Injection::plosives:  return "plosives";
            case Injection::none:      break;
        }
        return "";
    }

    float injectionHz (Injection i)
    {
        return i == Injection::mud ? 300.0f : (i == Injection::boxy ? 700.0f : (i == Injection::resonance ? 3500.0f : 0.0f));
    }

