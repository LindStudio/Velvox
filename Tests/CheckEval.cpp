    std::optional<automix::CapturedAudio> loadVocal (const juce::File& file, double maxSeconds)
    {
        juce::AudioFormatManager formats;
        formats.registerBasicFormats();
        std::unique_ptr<juce::AudioFormatReader> reader (formats.createReaderFor (file));
        if (reader == nullptr)
            return std::nullopt;
        const int channels = juce::jlimit (1, 2, (int) reader->numChannels);
        const int n = (int) std::min<juce::int64> (reader->lengthInSamples, (juce::int64) (reader->sampleRate * maxSeconds));
        juce::AudioBuffer<float> b (channels, n);
        reader->read (&b, 0, n, 0, true, channels > 1);
        automix::CapturedAudio a;
        a.sampleRate = reader->sampleRate;
        a.channels = channels;
        for (int c = 0; c < channels; ++c)
            a.vocal.emplace_back (b.getReadPointer (c), b.getReadPointer (c) + n);
        return a;
    }

    dsp::AnalysisResult analyseCaptured (const automix::CapturedAudio& v, check::Genre genre)
    {
        dsp::CheckModule check;
        check.setEnabled (true);
        dsp::VocalAnalyzer analyzer (check);
        analyzer.setSampleRate (v.sampleRate);
        analyzer.setMode (dsp::VocalAnalyzer::Mode::capture);
        analyzer.startCapture();
        const int n = v.numSamples();
        for (int start = 0; start < n; start += 512)
        {
            const int len = std::min (512, n - start);
            const float* ch[2] { v.vocal[0].data() + start, v.vocal[v.vocal.size() > 1 ? 1 : 0].data() + start };
            check.process (ch, 2, len);
            analyzer.pump();
        }
        juce::ignoreUnused (genre);
        return analyzer.analyse();
    }

    int runCheckTemplate (const juce::File& outFile, const juce::StringArray& wavs)
    {
        constexpr int nb = dsp::VocalAnalyzer::numBands;
        struct Curve { std::vector<float> db; bool high; };
        std::vector<Curve> curves;
        for (auto& path : wavs)
        {
            const auto v = loadVocal (juce::File (path), 120.0);
            if (! v.has_value())
            {
                std::printf ("cannot read %s\n", path.toRawUTF8());
                continue;
            }
            const auto r = analyseCaptured (*v, check::Genre::party);
            if (! r.enoughMaterial || r.smoothDb.size() != (size_t) nb)
                continue;
            curves.push_back ({ r.smoothDb, r.highVoice });
            std::printf ("%-48s f0 %6.1f (low %6.1f) %s\n", juce::File (path).getFileName().toRawUTF8(), r.f0MedianHz, r.f0LowHz,
                         r.highVoice ? "high" : "low");
        }

        juce::String out;
        out << "#pragma once\n// Generated by VelvoxTests --check-template from " << (int) curves.size()
            << " dry vocals (VocalSet v1.1 train singers, excerpts).\n"
               "// Long-term spectrum, 1/12-octave grid from 40 Hz, 1/3-octave smoothed, median-normalised over 150 Hz - 8 kHz.\n"
               "namespace velvox::check::voicetemplate\n{\n    inline constexpr int numBands = " << nb << ";\n";

        for (bool high : { false, true })
        {
            std::vector<const Curve*> set;
            for (auto& c : curves)
                if (c.high == high)
                    set.push_back (&c);
            std::vector<double> mean ((size_t) nb, 0.0), sd ((size_t) nb, 0.0);
            std::vector<float> offsets (set.size(), 0.0f);
            const auto valid = [] (float v) { return v > -190.0f; };
            for (int iteration = 0; iteration < 5; ++iteration)
            {
                std::vector<double> sum ((size_t) nb, 0.0);
                std::vector<int> cnt ((size_t) nb, 0);
                for (size_t i = 0; i < set.size(); ++i)
                    for (int b = 0; b < nb; ++b)
                        if (valid (set[i]->db[(size_t) b]))
                        {
                            sum[(size_t) b] += set[i]->db[(size_t) b] - offsets[i];
                            ++cnt[(size_t) b];
                        }
                for (int b = 0; b < nb; ++b)
                    mean[(size_t) b] = cnt[(size_t) b] > 0 ? sum[(size_t) b] / cnt[(size_t) b] : -200.0;
                // Normalise: the template is 0 dB at the median over 150 Hz - 8 kHz
                {
                    std::vector<double> m;
                    for (int b = 0; b < nb; ++b)
                        if (dsp::VocalAnalyzer::bandCentre (b) >= 150.0f && dsp::VocalAnalyzer::bandCentre (b) <= 8000.0f && mean[(size_t) b] > -190.0)
                            m.push_back (mean[(size_t) b]);
                    std::nth_element (m.begin(), m.begin() + (long) (m.size() / 2), m.end());
                    const double med = m.empty() ? 0.0 : m[m.size() / 2];
                    for (auto& v : mean)
                        if (v > -190.0)
                            v -= med;
                }
                for (size_t i = 0; i < set.size(); ++i)
                {
                    std::vector<float> d;
                    for (int b = 0; b < nb; ++b)
                        if (dsp::VocalAnalyzer::bandCentre (b) >= 150.0f && dsp::VocalAnalyzer::bandCentre (b) <= 8000.0f
                            && valid (set[i]->db[(size_t) b]) && mean[(size_t) b] > -190.0)
                            d.push_back (set[i]->db[(size_t) b] - (float) mean[(size_t) b]);
                    std::nth_element (d.begin(), d.begin() + (long) (d.size() / 2), d.end());
                    offsets[i] = d.empty() ? 0.0f : d[d.size() / 2];
                }
            }
            for (int b = 0; b < nb; ++b)
            {
                double s = 0.0;
                int k = 0;
                for (size_t i = 0; i < set.size(); ++i)
                    if (valid (set[i]->db[(size_t) b]))
                    {
                        const double e = set[i]->db[(size_t) b] - offsets[i] - mean[(size_t) b];
                        s += e * e;
                        ++k;
                    }
                sd[(size_t) b] = k > 1 ? std::sqrt (s / (k - 1)) : 6.0;
            }
            // Bands without bins (very low frequencies): nearest valid value
            for (int b = 0; b < nb; ++b)
                if (mean[(size_t) b] < -190.0)
                    for (int j = b + 1; j < nb; ++j)
                        if (mean[(size_t) j] > -190.0)
                        {
                            mean[(size_t) b] = mean[(size_t) j];
                            sd[(size_t) b] = sd[(size_t) j];
                            break;
                        }

            const auto writeArray = [&out] (const char* name, const std::vector<double>& v, int count)
            {
                out << "    // " << count << " voices\n    inline constexpr float " << name << "[numBands] {";
                for (size_t b = 0; b < v.size(); ++b)
                    out << (b % 8 == 0 ? "\n        " : " ") << juce::String (v[b], 2) << "f,";
                out << "\n    };\n";
            };
            writeArray (high ? "highVoice" : "lowVoice", mean, (int) set.size());
            writeArray (high ? "highVoiceSpread" : "lowVoiceSpread", sd, (int) set.size());
        }
        out << "}\n";
        if (! outFile.replaceWithText (out, false, false, "\n"))
        {
            std::printf ("cannot write %s\n", outFile.getFullPathName().toRawUTF8());
            return 1;
        }
        std::printf ("wrote %s (%d voices)\n", outFile.getFullPathName().toRawUTF8(), (int) curves.size());
        return 0;
    }

